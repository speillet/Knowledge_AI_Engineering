from dataclasses import dataclass
import html
import json
import os
from pathlib import Path
import re
import shutil
from typing import Any
import unicodedata
from urllib.parse import quote, unquote

from lint_flashcards import MOC, ROOT, Card, markdown_lines, parse_cards, topic_title
from sync_catalog import topic_order

REPOSITORY = "https://github.com/speillet/Knowledge_AI_Engineering"
WEBSITE = Path("website")
WIKI = re.compile(r"\[\[([^\]|#]+)(?:#([^\]|]+))?(?:\|([^\]]+))?\]\]")
MARKDOWN_LINK = re.compile(r"(?<!!)\[([^\]\n]*)\]\(([^)\s]+)\)")
RENDERED_LINK = re.compile(r"\[([^\]\n]+)\]\((\{\{<[^>]*>\}\}|[^)\s]+)\)")
CODE_SPAN = re.compile(r"(`+[^`]*`+)")
SHORTCODE = re.compile(r"\{\{[<%]")
METADATA = re.compile(r"<!--\s*(?:anki:|SR:|summary:|Generated by|catalog:).*?-->")
SUMMARY = re.compile(r"<!--\s*summary:\s*(.*?)\s*-->", re.S)
VERIFIED = re.compile(r"^Verified on:\s*(\d{1,2} \w+ \d{4})")
HEADING = re.compile(r"^(#{2,3})\s+(.+?)\s*$")
FOOTER = re.compile(r"^\[[^\]]+\]\([^)]+\)(?:\s*·\s*\[[^\]]+\]\([^)]+\))+\s*$")
LIST_ITEM = re.compile(r"^(?:(?P<num>\d+)\.|-)\s+(?P<body>.+)$")
LINKED_ITEM = re.compile(
    r"^(?:\*\*)?\[(?P<label>[^\]]+)\]\((?P<url>\{\{<[^>]*>\}\}|[^)\s]+)\)(?:\*\*)?(?:\s*(?:—|\u2013|:)\s*(?P<desc>.+))?$"
)
CONNECTION = re.compile(r"^\[\[([^\]|#]+)(?:#[^\]|]+)?(?:\|([^\]]+))?\]\]\s*(?:—\s*(.*))?$")
KINDS = (
    ("concept", "Key concepts", ""),
    ("confuse", "Do not confuse", "Do not confuse:"),
    ("calculation", "Calculations", "Calculation:"),
    ("scenario", "Scenarios", "Scenario:"),
)
NOUNS = {
    "concept": ("key concept", "key concepts"),
    "confuse": ("do-not-confuse", "do-not-confuse"),
    "calculation": ("calculation", "calculations"),
    "scenario": ("scenario", "scenarios"),
}

Convert = Callable[[str], str]


@dataclass
class Topic:
    """What domain pages, the catalog and the home page need to know about a topic."""

    source: Path
    title: str
    summary: str
    covers: list[str]
    counts: dict[str, int]
    cards: int


def source_pages(root: Path) -> list[Path]:
    """Select public documentation only, excluding environment and private editor files."""
    return sorted(
        {
            *(root / name for name in ("README.md", "START_HERE.md", "CONTRIBUTING.md", f"{MOC}.md")),
            *root.glob("[0-9]*/*.md"),
            *(root / "docs").rglob("*.md"),
            root / "examples/README.md",
            *root.glob("examples/*/README.md"),
        }
    )


def content_path(source: Path) -> Path:
    """Hugo content path: a directory README becomes its section index, the root README the home page."""
    return source.with_name("_index.md") if source.name == "README.md" else source


def ref(source: Path, fragment: str = "") -> str:
    """Shortcode resolving a staged page to its URL; Hugo stops on a broken reference."""
    target = "/" + content_path(source).as_posix() + (f"#{fragment}" if fragment else "")
    return '{{< relref "' + target + '" >}}'


def anchor(text: str) -> str:
    """ASCII heading slug, shared by generated ids and by links to headings."""
    text = unicodedata.normalize("NFKD", text).encode("ascii", "ignore").decode("ascii")
    return re.sub(r"[-\s]+", "-", re.sub(r"[^\w\s-]", "", text).strip().lower()) or "section"


def plain(text: str) -> str:
    """Inline Markdown reduced to its readable text, for summaries and search."""
    text = WIKI.sub(lambda m: m[3] or m[2] or m[1], text)
    text = RENDERED_LINK.sub(r"\1", text)
    text = re.sub(r"`+([^`]*)`+", r"\1", text)
    return re.sub(r"\*\*(.+?)\*\*|__(.+?)__", lambda m: m[1] or m[2], METADATA.sub("", text)).strip()


def inline_html(text: str) -> str:
    """Render inline Markdown placed inside HTML: code, emphasis and links, with relref kept intact."""
    tokens: list[str] = []

    def keep(fragment: str) -> str:
        tokens.append(fragment)
        return f"\x00{len(tokens) - 1}\x00"

    def link(match: re.Match[str]) -> str:
        label, url = match.groups()
        href = url if url.startswith("{{<") else html.escape(url)
        return keep(f'<a href="{href}">{html.escape(plain(label), quote=False)}</a>')

    text = CODE_SPAN.sub(lambda m: keep("<code>" + html.escape(m[1].strip("`").strip()) + "</code>"), text)
    text = html.escape(RENDERED_LINK.sub(link, text), quote=False)
    text = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", text)
    text = re.sub(r"(?<![\w*])\*(?!\s)(.+?)(?<!\s)\*(?![\w*])", r"<em>\1</em>", text)
    return re.sub("\x00(\\d+)\x00", lambda m: tokens[int(m[1])], text)


def link_converter(source: Path, pages: set[Path], wikilinks: dict[str, Path]) -> Convert:
    """Rewrite the links of one Markdown line or fragment; code spans are left untouched."""

    def wiki(match: re.Match[str]) -> str:
        name, heading, label = match.groups()
        target = wikilinks.get(name.strip())
        if target is None:
            raise ValueError(f"{source}: unknown wikilink {name}")
        return f"[{label or heading or name}]({ref(target, anchor(heading) if heading else '')})"

    def markdown_link(match: re.Match[str]) -> str:
        label, url = match.groups()
        if re.match(r"[a-zA-Z][a-zA-Z0-9+.-]*:", url) or url.startswith(("#", "/")):
            return match[0]
        path, _, fragment = url.partition("#")
        target = Path(os.path.normpath(source.parent / unquote(path)))
        if target in pages:
            return f"[{label}]({ref(target, fragment)})"
        suffix = f"#{fragment}" if fragment else ""
        return f"[{label}]({REPOSITORY}/blob/main/{quote(target.as_posix())}{suffix})"

    def convert(text: str) -> str:
        parts = CODE_SPAN.split(text)
        for i, part in enumerate(parts):
            if not part.startswith("`"):
                parts[i] = WIKI.sub(wiki, MARKDOWN_LINK.sub(markdown_link, METADATA.sub("", part)))
        return "".join(parts)

    return convert


def convert_block(markdown: str, convert: Convert) -> str:
    """Apply a line converter outside fenced code blocks."""
    return "\n".join(line if code else convert(line).rstrip() for _, line, code in markdown_lines(markdown))


def split_points(summary: str) -> list[str]:
    """Split a topic summary into its points, ignoring separators inside parentheses."""
    points: list[str] = []
    depth, current = 0, ""
    for char in summary.strip().rstrip("."):
        depth += (char == "(") - (char == ")")
        if char in ",;" and depth == 0:
            points.append(current.strip())
            current = ""
        else:
            current += char
    points.append(current.strip())
    return [p[:1].upper() + p[1:] for p in points if p]


def count_text(counts: dict[str, int]) -> str:
    """Card counts in words, for example "12 key concepts · 2 scenarios"."""
    parts = []
    for kind, (one, many) in NOUNS.items():
        if counts.get(kind):
            parts.append(f"{counts[kind]} {one if counts[kind] == 1 else many}")
    return " · ".join(parts)


class Ids:
    """Unique HTML ids within one page."""

    def __init__(self) -> None:
        self.seen: set[str] = set()

    def __call__(self, text: str) -> str:
        base = candidate = anchor(text)
        number = 2
        while candidate in self.seen:
            candidate = f"{base}-{number}"
            number += 1
        self.seen.add(candidate)
        return candidate


def fold(cls: str, ident: str, summary: str, body: str, *, is_open: bool = False) -> str:
    """A collapsible block; blank lines let Hugo render the Markdown inside the HTML."""
    attribute = " open" if is_open else ""
    return "\n".join(
        [
            f'<details class="{cls}" id="{ident}"{attribute}>',
            f'<summary><span class="kv-fold-title">{summary}</span>'
            '<span class="kv-chevron" aria-hidden="true"></span></summary>',
            '<div class="kv-fold-body">',
            "",
            body.strip("\n"),
            "",
            "</div>",
            "</details>",
            "",
        ]
    )


def fold_subsections(markdown: str, ids: Ids) -> str:
    """Keep `##` sections as headings and fold each `###` subsection into a collapsible block."""
    lines = list(markdown_lines(markdown))
    found: list[tuple[int, re.Match[str]]] = []
    for index, (_, line, code) in enumerate(lines):
        heading = None if code else HEADING.match(line)
        if heading:
            found.append((index, heading))
    output = [line for _, line, _ in lines[: found[0][0]]] if found else [line for _, line, _ in lines]
    for k, (index, match) in enumerate(found):
        end = found[k + 1][0] if k + 1 < len(found) else len(lines)
        body = [line for _, line, _ in lines[index + 1 : end]]
        if len(match[1]) == 2:
            output += [lines[index][1], *body]
            continue
        title = match[2]
        output += ["", fold("kv-fold", ids(plain(title)), f"<h3>{inline_html(title)}</h3>", "\n".join(body))]
    return "\n".join(output).strip("\n")


def link_cards(items: list[re.Match[str]], links: list[re.Match[str]], ordered: bool) -> str:
    """A list of links becomes a grid of cards; ordered lists keep their step numbers."""
    rows = []
    for item, link in zip(items, links, strict=True):
        url = link["url"]
        href = url if url.startswith("{{<") else html.escape(url)
        number = f'<span class="kv-step-num">{item["num"]}</span>' if ordered else ""
        desc = f'<span class="kv-link-desc">{inline_html(link["desc"])}</span>' if link["desc"] else ""
        title = html.escape(plain(link["label"]), quote=False)
        rows.append(f'<li class="kv-link">{number}<a class="kv-link-title" href="{href}">{title}</a>{desc}</li>')
    compact = "" if ordered or any(link["desc"] for link in links) else " kv-compact"
    tag, cls = ("ol", "kv-grid kv-steps") if ordered else ("ul", f"kv-grid{compact}")
    return f'<{tag} class="{cls} not-prose">\n' + "\n".join(rows) + f"\n</{tag}>"


def cardify_lists(markdown: str) -> str:
    """Turn lists made only of links, optionally followed by a description, into card grids.

    Lists with nested items, continuation lines or other content stay Markdown lists.
    """
    lines = list(markdown_lines(markdown))
    output: list[str] = []
    i = 0
    while i < len(lines):
        _, line, code = lines[i]
        if code or not LIST_ITEM.match(line):
            output.append(line)
            i += 1
            continue
        j = i
        items: list[re.Match[str]] = []
        while j < len(lines):
            item = None if lines[j][2] else LIST_ITEM.match(lines[j][1])
            if item is None:
                break
            items.append(item)
            j += 1
        links = [LINKED_ITEM.match(item["body"].strip()) for item in items]
        ordered = [bool(item["num"]) for item in items]
        continued = j < len(lines) and lines[j][1][:1] in (" ", "\t") and bool(lines[j][1].strip())
        if len(items) >= 3 and all(links) and not continued and (all(ordered) or not any(ordered)):
            valid = [link for link in links if link]
            output += ["", link_cards(items, valid, ordered=all(ordered)), ""]
        else:
            output += [entry[1] for entry in lines[i:j]]
        i = j
    return "\n".join(output)


def split_footer(markdown: str) -> tuple[str, str]:
    """Separate a final line made only of navigation links, shown after the page."""
    lines = markdown.rstrip().split("\n")
    if lines and FOOTER.match(lines[-1].strip()):
        return "\n".join(lines[:-1]).rstrip(), lines[-1].strip()
    return markdown, ""


def front_matter(data: dict[str, Any]) -> str:
    """JSON front matter: unambiguous for card separators and safe for any string."""
    return json.dumps(data, ensure_ascii=False, indent=1) + "\n\n"


def first_paragraph(markdown: str) -> str:
    """Readable first paragraph of a page, used as its description."""
    for block in re.split(r"\n\s*\n", markdown):
        block = block.strip()
        if block and not block.startswith(("#", "```", "<", "|", "-", "1.", ">", "[", "{{")):
            return plain(" ".join(block.split()))[:220]
    return ""


def kind_of(question: str) -> tuple[str, str, str]:
    """Card kind, section label and question prefix."""
    for kind, label, prefix in KINDS[1:]:
        if question.startswith(prefix):
            return kind, label, prefix
    return KINDS[0]


def card_id(card: Card, ids: Ids) -> str:
    """Stable anchor derived from the Anki identifier, so links to a card survive rewording."""
    return ids("c" + card.guid.encode("ascii").hex()[:12] if card.guid else card.question)


def render_card(card: Card, kind: str, prefix: str, ident: str, convert: Convert) -> str:
    question = card.question.removeprefix(prefix).strip() if prefix else card.question
    question = question[:1].upper() + question[1:]
    return "\n".join(
        [
            f'<details class="kv-card kv-{kind}" id="{ident}">',
            f'<summary><span class="kv-q">{inline_html(convert(question))}</span>'
            '<span class="kv-chevron" aria-hidden="true"></span></summary>',
            '<div class="kv-a">',
            "",
            convert_block(card.answer, convert),
            "",
            "</div>",
            "</details>",
            "",
        ]
    )


def section_bounds(text: str) -> dict[str, int]:
    """Line indexes of the Cards, Sources and Connections headings, outside code."""
    bounds: dict[str, int] = {}
    for index, (_, line, code) in enumerate(markdown_lines(text)):
        if not code and line.strip() in ("## Cards", "## Sources", "## Connections"):
            bounds.setdefault(line.strip()[3:], index)
    return bounds


def connection_list(block: str, convert: Convert, wikilinks: dict[str, Path]) -> list[str]:
    """Each connection becomes a card linking to the neighbor, with its rationale."""
    items: list[str] = []
    for line in block.splitlines():
        if not line.startswith("- "):
            continue
        body = line[2:].strip()
        match = CONNECTION.match(body)
        if match and match[1] == MOC:
            continue
        if match and match[1] in wikilinks:
            target = wikilinks[match[1]]
            label = html.escape(match[2] or match[1], quote=False)
            reason = f'<span class="kv-link-desc">{inline_html(plain(match[3]))}</span>' if match[3] else ""
            items.append(f'<li class="kv-link"><a class="kv-link-title" href="{ref(target)}">{label}</a>{reason}</li>')
        else:
            items.append(f'<li class="kv-link kv-plain">{inline_html(convert(body))}</li>')
    return items


def topic_page(
    source: Path, text: str, convert: Convert, wikilinks: dict[str, Path], weight: int
) -> tuple[dict[str, Any], str, Topic]:
    cards, malformed = parse_cards(text)
    if malformed:
        raise ValueError(f"{source}: malformed cards at lines {malformed}")
    lines = text.splitlines()
    tags = [t.lstrip("#") for t in lines[1].removeprefix("Tags:").split() if t.lstrip("#") != "flashcards"]
    verified = next((m[1] for m in map(VERIFIED.match, lines[1:4]) if m), "")
    summary_match = SUMMARY.search(text)
    summary = " ".join(summary_match[1].split()) if summary_match else ""
    covers = split_points(summary)
    bounds = section_bounds(text)
    ids = Ids()
    groups: dict[str, list[str]] = {kind: [] for kind, _, _ in KINDS}
    questions = []
    for card in cards:
        kind, _, prefix = kind_of(card.question)
        ident = card_id(card, ids)
        groups[kind].append(render_card(card, kind, prefix, ident, convert))
        questions.append({"q": plain(card.question), "id": ident, "k": kind})
    counts = {kind: len(items) for kind, items in groups.items()}
    section_ids = {label: ids(label) for _, label, _ in KINDS}
    section_ids |= {"Sources": ids("Sources"), "Connections": ids("Connections")}

    chips = [
        f'<a class="kv-chip kv-{kind}" href="#{section_ids[label]}"><b>{counts[kind]}</b> '
        f"{NOUNS[kind][0] if counts[kind] == 1 else NOUNS[kind][1]}</a>"
        for kind, label, _ in KINDS
        if counts[kind]
    ]
    if verified:
        chips.append(f'<span class="kv-chip kv-verified">Verified on {verified}</span>')
    blocks = ['<div class="kv-meta not-prose">\n' + "\n".join(chips) + "\n</div>"]
    if covers:
        point_items = "\n".join(f"<li>{html.escape(p, quote=False)}</li>" for p in covers)
        points = f'<ul class="kv-points not-prose">\n{point_items}\n</ul>'
        title = f'What this topic covers <span class="kv-count">{len(covers)}</span>'
        blocks.append(fold("kv-fold kv-covers", ids("What this topic covers"), title, points))
    blocks.append(
        '<div class="kv-tools not-prose">\n'
        '<button type="button" class="kv-btn" data-kv-expand>Expand all answers</button>\n'
        '<button type="button" class="kv-btn" data-kv-collapse>Collapse all</button>\n'
        "</div>"
    )
    if "Cards" in bounds:
        start = next(i for i, line in enumerate(lines) if line.startswith("<!-- summary:")) + 1
        intro = "\n".join(lines[start : bounds["Cards"]]).strip().removesuffix("---").strip()
        blocks.append(fold_subsections(cardify_lists(convert_block(intro, convert)), ids))
    for kind, label, _ in KINDS:
        if groups[kind]:
            body = '<div class="kv-cards">\n\n' + "\n".join(groups[kind]) + "\n</div>"
            blocks.append(f"## {label} {{#{section_ids[label]}}}\n\n{body}")
    if "Sources" in bounds:
        end = bounds.get("Connections", len(lines))
        sources = convert_block("\n".join(lines[bounds["Sources"] + 1 : end]).strip(), convert)
        if sources:
            count = sum(1 for line in sources.splitlines() if line.startswith("- "))
            heading = f'Primary sources <span class="kv-count">{count}</span>'
            folded = fold("kv-fold", ids("sources-list"), heading, sources)
            blocks.append(f"## Sources {{#{section_ids['Sources']}}}\n\n{folded}")
    if "Connections" in bounds:
        items = connection_list("\n".join(lines[bounds["Connections"] + 1 :]), convert, wikilinks)
        if items:
            grid = '<ul class="kv-grid not-prose">\n' + "\n".join(items) + "\n</ul>"
            blocks.append(f"## Connections {{#{section_ids['Connections']}}}\n\n{grid}")
    title = topic_title(text)
    front = {
        "title": title,
        "weight": weight,
        "description": summary[:200],
        "summary": summary,
        "params": {
            "source": source.as_posix(),
            "tags": tags,
            "verified": verified,
            "covers": covers,
            "counts": counts,
            "cards": len(cards),
            "questions": questions,
        },
    }
    return front, "\n\n".join(blocks), Topic(source, title, summary, covers, counts, len(cards))


def generic_page(source: Path, text: str, convert: Convert) -> tuple[dict[str, Any], str]:
    lines = text.splitlines()
    title = lines[0].removeprefix("# ").strip() if lines and lines[0].startswith("# ") else source.stem
    rest = lines[1:] if lines and lines[0].startswith("# ") else lines
    if rest and rest[0].startswith("Tags:"):
        rest = rest[1:]
    body = convert_block("\n".join(rest), convert)
    body, footer = split_footer(body)
    folded = fold_subsections(cardify_lists(body), Ids())
    if footer:
        folded += f'\n\n<nav class="kv-related not-prose" aria-label="Related pages">\n\n{footer}\n\n</nav>\n'
    front = {"title": title, "description": first_paragraph(body), "params": {"source": source.as_posix()}}
    return front, folded


def topic_tile(topic: Topic, number: str = "") -> str:
    """A topic card for the catalog and domain routes: title, card counts and covered points."""
    step = f'<span class="kv-step-num">{number}</span>' if number else ""
    points = "".join(f"<li>{html.escape(point, quote=False)}</li>" for point in topic.covers[:8])
    more = f'<li class="kv-more">+ {len(topic.covers) - 8} more</li>' if len(topic.covers) > 8 else ""
    noun = "point" if len(topic.covers) == 1 else "points"
    covers = (
        f'<details class="kv-tile-more"><summary>{len(topic.covers)} {noun} covered</summary>'
        f'<ul class="kv-points kv-small">{points}{more}</ul></details>'
        if topic.covers
        else ""
    )
    return (
        f'<li class="kv-tile">{step}<a class="kv-tile-title" href="{ref(topic.source)}">'
        f"{html.escape(topic.title, quote=False)}</a>"
        f'<span class="kv-tile-meta">{count_text(topic.counts)}</span>{covers}</li>'
    )


def domain_page(
    source: Path, info: dict[str, Any], topics: list[Topic], meta: dict[Path, Topic]
) -> tuple[dict[str, Any], str]:
    directory = source.parent
    number = directory.name.split("-", 1)[0]
    core = [meta[directory / name] for name in info.get("core", []) if directory / name in meta]
    prerequisites = [meta[Path(p)] for p in info.get("prerequisites", []) if Path(p) in meta]
    cards = sum(t.cards for t in topics)
    scenarios = sum(t.counts.get("scenario", 0) for t in topics)
    stats = "".join(
        f'<div class="kv-stat"><b>{value}</b><span>{label}</span></div>'
        for value, label in ((len(topics), "topics"), (cards, "cards"), (scenarios, "scenarios"))
    )
    blocks = [
        "{{< lead >}}\n" + info.get("intro", "") + "\n{{< /lead >}}",
        f'<div class="kv-stats not-prose">{stats}</div>',
    ]
    if prerequisites:
        pills = "".join(
            f'<a class="kv-pill" href="{ref(t.source)}">{html.escape(t.title, quote=False)}</a>' for t in prerequisites
        )
        blocks.append(
            "## Before you start {#before-you-start}\n\nRead these topics first if their vocabulary is new to you.\n\n"
            f'<div class="kv-pills not-prose">{pills}</div>'
        )
    if core:
        route = "\n".join(topic_tile(t, str(i)) for i, t in enumerate(core, 1))
        blocks.append("## Learn the fundamentals {#learn-the-fundamentals}\n\nWork through these topics in order.\n\n"
                      f'<ol class="kv-route not-prose">\n{route}\n</ol>')
    if info.get("practice"):
        blocks.append("## Put it into practice {#put-it-into-practice}\n\n"
                      f'<div class="kv-practice not-prose"><p>{html.escape(info["practice"], quote=False)}</p>'
                      "<p>Use the scenarios of each topic to check your reasoning before moving on.</p></div>")
    blocks.append('<div id="go-further"></div>\n\n## All topics {#all-topics}')
    front = {
        "title": info["title"],
        "weight": int(number),
        "description": info.get("intro", ""),
        "summary": info.get("intro", ""),
        "params": {"domain": True, "number": number, "source": source.as_posix()},
    }
    return front, "\n\n".join(blocks)


def catalog_body(intro: str, sections: dict[str, Any], topics_by_dir: dict[str, list[Topic]]) -> str:
    """The topic catalog: one collapsible block per domain, holding its topic cards."""
    blocks = [intro.strip()]
    ordered = sorted(sections.items(), key=lambda item: int(item[0].split("-", 1)[0]))
    for number, (directory, info) in enumerate(ordered):
        topics = topics_by_dir.get(directory, [])
        tiles = "\n".join(topic_tile(t) for t in topics)
        domain = directory.split("-", 1)[0]
        name = html.escape(info["title"], quote=False)
        title = f'<span class="kv-num">{domain}</span>{name} <span class="kv-count">{len(topics)}</span>'
        body = (f'<p class="kv-domain-intro">{html.escape(info.get("intro", ""), quote=False)} '
                f'<a href="{ref(Path(directory) / "README.md")}">Open the domain →</a></p>\n\n'
                f'<ul class="kv-tiles not-prose">\n{tiles}\n</ul>')
        ident = anchor(f"{domain} — {info['title']}")
        blocks.append(fold("kv-fold kv-domain", ident, title, body, is_open=number == 0))
    return "\n\n".join(blocks)


def prepare(root: Path = ROOT) -> Path:
    """Rebuild the disposable Hugo content from the selected public pages."""
    sources = source_pages(root)
    pages = {p.relative_to(root) for p in sources}
    wikilinks = {p.stem: p for p in pages if p.name != "README.md"}
    sections = json.loads((root / "scripts/sections.json").read_text(encoding="utf-8"))
    content = root / WEBSITE / "content"
    if content.exists():
        shutil.rmtree(content)
    texts = {path.relative_to(root): path.read_text(encoding="utf-8") for path in sources}
    for source, text in texts.items():
        if SHORTCODE.search(text):
            raise ValueError(f"{source}: '{{{{<' or '{{{{%' would be read as a Hugo shortcode")
    paths_by_dir: dict[str, list[Path]] = {}
    for page in pages:
        if re.match(r"^\d", page.parts[0]) and len(page.parts) == 2 and page.name != "README.md":
            paths_by_dir.setdefault(page.parts[0], []).append(page)
    for paths in paths_by_dir.values():
        paths.sort(key=topic_order)
    staged: dict[Path, tuple[dict[str, Any], str]] = {}
    meta: dict[Path, Topic] = {}
    for paths in paths_by_dir.values():
        for weight, source in enumerate(paths, 1):
            convert = link_converter(source, pages, wikilinks)
            front, body, topic = topic_page(source, texts[source], convert, wikilinks, weight)
            staged[source] = (front, body)
            meta[source] = topic
    topics_by_dir = {d: [meta[p] for p in paths] for d, paths in paths_by_dir.items()}
    for source, text in texts.items():
        if source in staged:
            continue
        top = source.parts[0]
        convert = link_converter(source, pages, wikilinks)
        if source == Path("README.md"):
            description = first_paragraph(text.split("\n", 1)[1])
            staged[source] = ({"title": "AI Engineering", "description": description, "aliases": ["/search.html"]}, "")
        elif re.match(r"^\d", top) and source.name == "README.md":
            staged[source] = domain_page(source, sections[top], topics_by_dir.get(top, []), meta)
        elif source == Path("docs/catalog.md"):
            front, _ = generic_page(source, text, convert)
            intro = convert_block(text.split("<!-- catalog:begin -->")[0].split("\n", 1)[1], convert)
            staged[source] = (front, catalog_body(intro, sections, topics_by_dir))
        else:
            staged[source] = generic_page(source, text, convert)
    for source, (front, body) in staged.items():
        target = content / content_path(source)
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(front_matter(front) + body.rstrip() + "\n", encoding="utf-8")
    cards = sum(t.cards for t in meta.values())
    print(f"Staged {len(staged)} pages, {len(meta)} topics and {cards} cards in {content.relative_to(root)}")
    return content


if __name__ == "__main__":
    prepare()
