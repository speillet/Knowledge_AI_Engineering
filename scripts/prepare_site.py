#!/usr/bin/env python3
"""Stage the vault as Hugo content for the Blowfish theme, without modifying the sources.

Topic pages keep one section per card kind — key concepts, do-not-confuse, calculations
and scenarios — and fold every answer under its question. Other pages keep their `##`
sections and fold each `###` into a collapsible block; lists made only of links become
card grids. Domain pages, the topic catalog and the home page are built from the
topics. Links become `relref` shortcodes, so Hugo fails the build on a broken link.

The generated `website/content` tree is disposable: `make site` rebuilds it, then the
static site in `site/`.
"""

