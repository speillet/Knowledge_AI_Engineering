#!/usr/bin/env python3
"""Generate the topic catalog and MOC from topics and sections.json.

python3 scripts/sync_catalog.py # updates both blocks
python3 scripts/sync_catalog.py --check # fails if an update is required
"""

import argparse
import json
import os
from pathlib import Path
import re

from lint_flashcards import CATALOG, MOC, README, ROOT, topic_title

BEGIN = "<!-- catalog:begin -->"
END = "<!-- catalog:end -->"


def section_files(root: Path, directory: str) -> list[Path]:
    """Include flashcard topics, including the historical container index."""
    return sorted((p for p in (root / directory).glob("*.md") if p.name != README), key=topic_order)


def render_domain(root: Path, directory: str) -> str:
    """Generate a domain entry point without adding it to the card collection."""
    info = json.loads((root / "scripts/sections.json").read_text(encoding="utf-8"))[directory]
    files = section_files(root, directory)
    core = [root / directory / name for name in info["core"]]
    prerequisites = [root / name for name in info["prerequisites"]]
    if not core or len(set(core)) != len(core) or not set(core) <= set(files):
        raise ValueError(f"{directory}: core topics must be unique existing topics in this domain")
    available = {p for section in root.glob("[0-9]*") if section.is_dir() for p in section_files(root, section.name)}
    if not set(prerequisites) <= available:
        raise ValueError(f"{directory}: prerequisites must refer to existing topics")

    def link(path: Path) -> str:
        title = topic_title(path.read_text(encoding="utf-8"))
        return f"[{title}]({Path(os.path.relpath(path, root / directory)).as_posix()})"

    output = [
        f"# {info['title']}",
        "",
        "<!-- Generated by scripts/sync_catalog.py; edit scripts/sections.json. -->",
        "",
        info["intro"],
        "",
        "## Before you start",
        "",
    ]
    output += [f"- {link(p)}" for p in prerequisites] or [
        "No other vault topic is required. Start with the sequence below."
    ]
    output += ["", "## Learn the fundamentals", "", "Work through these topics in order:", ""]
    output += [f"{i}. {link(p)}" for i, p in enumerate(core, 1)]
    output += [
        "",
        "## Go further",
        "",
        "Choose these topics as your project requires; they are not prerequisites for getting started.",
        "",
    ]
    output += [f"- {link(p)}" for p in files if p not in core]
    output += [
        "",
        "## Put it into practice",
        "",
        info["practice"],
        "",
        "Use the scenarios in each topic to check your reasoning before moving on.",
        "",
        "[Learning paths](../docs/paths/README.md) · [Topic catalog](../docs/catalog.md) · "
        "[Map of content](../00-moc-ai-engineering.md)",
        "",
    ]
    return "\n".join(output)


def topic_order(path: Path) -> tuple[int, str]:
    """Compatibility with 31-... and extension 30-010-... without renaming the existing one."""
    section = int(path.parent.name.split("-", 1)[0])
    parts = path.stem.split("-")
    if len(parts) > 2 and int(parts[0]) == section and parts[1].isdigit():
        number = int(parts[1])
    else:
        number = int(parts[0]) if section == 70 else int(parts[0]) - section
    return number, path.name


def render(root: Path, moc: bool = False) -> str:
    """Render wikilinks for the MOC or relative Markdown links for the catalog."""
    sections = json.loads((root / "scripts/sections.json").read_text(encoding="utf-8"))
    unknown = {p.name for p in root.glob("[0-9]*") if p.is_dir()} - sections.keys()
    if unknown:
        raise ValueError(f"missing sections of scripts/sections.json: {sorted(unknown)}")
    output = []
    for directory, info in sorted(sections.items(), key=lambda item: int(item[0].split("-")[0])):
        files = section_files(root, directory)
        if not files:
            raise ValueError(f"Empty or non-existent section: {directory}")
        output += [f"{'##' if moc else '###'} {directory.split('-')[0]} — {info['title']}", ""]
        output += [f"[Start this domain]({'..' if not moc else '.'}/{directory}/README.md)", ""]
        if not moc and info.get("intro"):
            output += [info["intro"], ""]
        for path in files:
            text = path.read_text(encoding="utf-8")
            title = topic_title(text)
            match = re.search(r"^<!-- summary: (.+) -->$", text, re.M)
            if not match:
                raise ValueError(f"{path.name} : missing summary comment")
            if moc:
                output.append(f"- [[{path.stem}|{title}]]")
            else:
                output.append(f"- [{title}](../{path.relative_to(root).as_posix()}) : {match[1]}")
        output.append("")
    return "\n".join(output).rstrip()


def replace_block(text: str, body: str) -> str:
    """Replaces content between catalog delimiters."""
    if text.count(BEGIN) != 1 or text.count(END) != 1 or text.index(BEGIN) > text.index(END):
        raise ValueError("catalog delimiters absent, duplicated or reversed")
    before, rest = text.split(BEGIN)
    _, after = rest.split(END)
    return before + BEGIN + "\n\n" + body + "\n\n" + END + after


def sync(root: Path = ROOT, check: bool = False) -> bool:
    """Updates the two summaries; with check, returns False if they are to be regenerated, without writing."""
    updates: list[tuple[Path, str]] = []
    for name, moc in ((CATALOG, False), (f"{MOC}.md", True)):
        path = root / name
        original = path.read_text(encoding="utf-8")
        updated = replace_block(original, render(root, moc=moc))
        if updated != original:
            updates.append((path, updated))
    sections = json.loads((root / "scripts/sections.json").read_text(encoding="utf-8"))
    for directory in sections:
        path = root / directory / README
        updated = render_domain(root, directory)
        if not path.exists() or path.read_text(encoding="utf-8") != updated:
            updates.append((path, updated))
    for path, updated in updates:
        if not check:
            path.write_text(updated, encoding="utf-8", newline="\n")
        print(f"{path.name} : {('needs regeneration' if check else 'updated')}")
    return not updates if check else True


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    try:
        return 0 if sync(check=args.check) else 1
    except (ValueError, OSError) as exc:
        parser.exit(1, f"ERROR: {exc}\n")


if __name__ == "__main__":
    raise SystemExit(main())
